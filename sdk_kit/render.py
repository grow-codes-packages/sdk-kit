"""Render the template for one service: tokens, category blocks and category paths (SPEC section 0)."""

from __future__ import annotations

import fnmatch
import json
import os
import re
import stat
from collections.abc import Iterator, Mapping
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

from sdk_kit import __version__
from sdk_kit.kit import Kit
from sdk_kit.services import CATEGORIES, DEFAULT_PACKAGE_VERSION, LANGS, Service

GENERATED_MARKER = "Generated by sdk-kit"
HEADER_SCAN_LINES = 10
TEMPLATE_CONFIG = "template.json"

# Build output and caches that language agents may leave inside the template while testing it.
IGNORED_NAMES = frozenset(
    {
        ".DS_Store",
        ".coverage",
        ".gradle",
        ".idea",
        ".mypy_cache",
        ".nox",
        ".pytest_cache",
        ".ruff_cache",
        ".tox",
        ".venv",
        "__pycache__",
        "coverage",
        "dist",
        "htmlcov",
        "node_modules",
        "target",
        "venv",
    }
)
IGNORED_SUFFIXES = (".pyc", ".pyo", ".egg-info")

CATEGORY_SEGMENT_RE = re.compile(r"^_?(secrets|logging|tracing)(?:[_.-]|$)")

_MARKER_START_RE = re.compile(r"^\s*(?://|#|<!--|/\*|--)\s*@sdk-kit:")
_MARKER_RE = re.compile(
    r"^\s*(?://|#|<!--|/\*|--)\s*@sdk-kit:"
    r"(?:(?P<if>if)\s+(?P<expr>[^\s].*?)|(?P<endif>endif))"
    r"\s*(?:-->|\*/)?\s*$"
)
_ANY_RE = re.compile(r"^any\(\s*([a-z]+(?:\s*,\s*[a-z]+)*)\s*\)$")


class RenderError(ValueError):
    """The template is malformed (bad marker, unknown category, path collision...)."""


def token_pattern(names: list[str] | tuple[str, ...] | Mapping[str, str]) -> re.Pattern[str]:
    """Regex matching ``__NAME__`` for the given names, longest names first."""
    ordered = sorted(names, key=len, reverse=True)
    return re.compile("__(" + "|".join(re.escape(name) for name in ordered) + ")__")


def replace_tokens(text: str, tokens: Mapping[str, str]) -> str:
    """Replace every ``__NAME__`` token (``GROW___KEY_UPPER___URL`` -> ``GROW_OPENBAO_URL``)."""
    pattern = token_pattern(tokens)
    return pattern.sub(lambda match: tokens[match.group(1)], text)


def _parse_condition(expr: str, where: str) -> frozenset[str]:
    """Categories named by ``secrets`` or ``any(logging,tracing)``."""
    expr = expr.strip()
    match = _ANY_RE.match(expr)
    names = [n.strip() for n in match.group(1).split(",")] if match else [expr]
    unknown = [name for name in names if name not in CATEGORIES]
    if unknown:
        raise RenderError(f"{where}: unknown category in @sdk-kit:if {expr!r}")
    return frozenset(names)


def apply_blocks(text: str, categories: tuple[str, ...] | frozenset[str], where: str = "<text>") -> str:
    """Keep ``@sdk-kit:if`` blocks for present categories; always drop the marker lines."""
    if "@sdk-kit:" not in text:
        return text
    present = set(categories)
    out: list[str] = []
    open_line: int | None = None
    keep = True
    for number, line in enumerate(text.splitlines(keepends=True), start=1):
        if not _MARKER_START_RE.match(line):
            if keep:
                out.append(line)
            continue
        match = _MARKER_RE.match(line.rstrip("\r\n"))
        if match is None:
            raise RenderError(f"{where}:{number}: malformed @sdk-kit marker: {line.strip()!r}")
        if match.group("if"):
            if open_line is not None:
                raise RenderError(
                    f"{where}:{number}: @sdk-kit:if inside the block opened on line {open_line} "
                    "(blocks do not nest)"
                )
            wanted = _parse_condition(match.group("expr"), f"{where}:{number}")
            open_line = number
            keep = bool(wanted & present)
        else:
            if open_line is None:
                raise RenderError(f"{where}:{number}: @sdk-kit:endif without @sdk-kit:if")
            open_line = None
            keep = True
    if open_line is not None:
        raise RenderError(f"{where}:{open_line}: @sdk-kit:if is never closed")
    return "".join(out)


def is_generated_text(text: str) -> bool:
    """True when the file carries the "Generated by sdk-kit" header in its first lines."""
    head = text.split("\n", HEADER_SCAN_LINES)[:HEADER_SCAN_LINES]
    return any(GENERATED_MARKER in line for line in head)


def is_generated_bytes(data: bytes) -> bool:
    """:func:`is_generated_text` for raw file content (binary files are never generated)."""
    text = decode_text(data)
    return text is not None and is_generated_text(text)


def decode_text(data: bytes) -> str | None:
    """UTF-8 text, or ``None`` for binary content (NUL byte or invalid UTF-8)."""
    if b"\0" in data[:8192]:
        return None
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError:
        return None


@dataclass(frozen=True)
class TemplateConfig:
    """``template.json`` of one template source: extra category paths."""

    categories: Mapping[str, tuple[str, ...]]

    @classmethod
    def load(cls, source: Path) -> TemplateConfig:
        path = source / TEMPLATE_CONFIG
        if not path.is_file():
            return cls({})
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            raise RenderError(f"{path}: invalid JSON: {exc}") from exc
        raw = data.get("categories", {}) if isinstance(data, dict) else None
        if not isinstance(raw, dict):
            raise RenderError(f"{path}: 'categories' must be an object")
        cats: dict[str, tuple[str, ...]] = {}
        for name, entries in raw.items():
            if name not in CATEGORIES:
                raise RenderError(f"{path}: unknown category {name!r}")
            if not isinstance(entries, list) or not all(isinstance(e, str) for e in entries):
                raise RenderError(f"{path}: categories.{name} must be a list of paths")
            cats[name] = tuple(e.strip("/") for e in entries)
        return cls(cats)


def _entry_matches(rel: str, entry: str) -> bool:
    return rel == entry or rel.startswith(entry + "/") or fnmatch.fnmatchcase(rel, entry)


def path_categories(rel: PurePosixPath, config: TemplateConfig, rendered: str | None = None) -> set[str]:
    """Categories a template path belongs to (segment rule + ``template.json``)."""
    found = {m.group(1) for part in rel.parts if (m := CATEGORY_SEGMENT_RE.match(part))}
    candidates = [rel.as_posix()] + ([rendered] if rendered else [])
    for name, entries in config.categories.items():
        if any(_entry_matches(c, e) for c in candidates for e in entries):
            found.add(name)
    return found


@dataclass(frozen=True)
class RenderedFile:
    """One output file (or symlink) of a rendered repository."""

    path: str  # posix path relative to the repo root
    data: bytes = b""
    mode: int = 0o644
    link: str | None = None  # symlink target (relative), when this entry is a symlink
    generated: bool = False  # carries the "Generated by sdk-kit" header (sdk-kit owns it)
    source: str = ""  # where it came from, for messages

    @property
    def is_link(self) -> bool:
        return self.link is not None


@dataclass(frozen=True)
class Source:
    """A template folder copied to ``dest`` in the repo."""

    root: Path
    dest: str
    raw: bool = False  # copy as-is: no tokens, no blocks (conformance, demo server)


def _walk(root: Path) -> Iterator[PurePosixPath]:
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(
            d for d in dirnames if d not in IGNORED_NAMES and not d.endswith(IGNORED_SUFFIXES)
        )
        base = Path(dirpath)
        # Symlinked directories are listed in dirnames but not followed; treat them as entries.
        entries = list(filenames) + [d for d in dirnames if (base / d).is_symlink()]
        for name in sorted(entries):
            if name in IGNORED_NAMES or name.endswith(IGNORED_SUFFIXES):
                continue
            yield PurePosixPath((base / name).relative_to(root).as_posix())


def sources_for(kit: Kit, service: Service) -> list[Source]:
    """Template folders and their destinations (see the brief's mapping)."""
    tpl = kit.template
    sources = [Source(tpl / "common", "")]
    sources += [Source(tpl / lang, lang) for lang in LANGS]
    sources.append(Source(tpl / "docker", "docker"))
    sources += [Source(tpl / "examples" / lang, f"examples/{lang}") for lang in LANGS]
    sources.append(Source(kit.conformance, "conformance", raw=True))
    sources.append(Source(kit.root / "spec" / "schemas", "conformance/schemas", raw=True))
    if service.key == "demo":
        sources.append(Source(kit.demo, "demo", raw=True))
    return [s for s in sources if s.root.is_dir()]


def _file_mode(st_mode: int) -> int:
    return 0o755 if stat.S_IMODE(st_mode) & 0o111 else 0o644


def render(
    kit: Kit, service: Service, package_version: str = DEFAULT_PACKAGE_VERSION
) -> dict[str, RenderedFile]:
    """Render the whole repository for ``service`` into memory: ``{path: RenderedFile}``."""
    tokens = service.tokens(package_version)
    present = set(service.categories)
    files: dict[str, RenderedFile] = {}

    def add(item: RenderedFile) -> None:
        other = files.get(item.path)
        if other is not None:
            raise RenderError(f"{item.path} is rendered from both {other.source} and {item.source}")
        files[item.path] = item

    for src in sources_for(kit, service):
        config = TemplateConfig({}) if src.raw else TemplateConfig.load(src.root)
        for rel in _walk(src.root):
            if rel.as_posix() == TEMPLATE_CONFIG and not src.raw:
                continue
            origin = src.root / rel
            rel_text = rel.as_posix() if src.raw else replace_tokens(rel.as_posix(), tokens)
            if path_categories(rel, config, rel_text) - present:
                continue
            out_path = f"{src.dest}/{rel_text}" if src.dest else rel_text
            source_name = origin.relative_to(kit.root).as_posix()
            if src.dest == "" and rel_text == "CLAUDE.md":
                continue  # always recreated below as a symlink to AGENTS.md
            if origin.is_symlink():
                target = str(origin.readlink())
                add(
                    RenderedFile(
                        out_path,
                        link=target if src.raw else replace_tokens(target, tokens),
                        source=source_name,
                    )
                )
                continue
            data = origin.read_bytes()
            mode = _file_mode(origin.stat().st_mode)
            text = None if src.raw else decode_text(data)
            if text is not None:
                text = apply_blocks(text, service.categories, source_name)
                text = replace_tokens(text, tokens)
                data = text.encode("utf-8")
            generated = text is not None and is_generated_text(text)
            add(RenderedFile(out_path, data=data, mode=mode, generated=generated, source=source_name))

    if "AGENTS.md" in files:
        add(RenderedFile("CLAUDE.md", link="AGENTS.md", source="sdk-kit"))
    if "conformance/VERSION" not in files and kit.conformance.is_dir():
        add(RenderedFile("conformance/VERSION", data=f"{__version__}\n".encode(), source="sdk-kit"))
    return dict(sorted(files.items()))


def conformance_paths(files: Mapping[str, RenderedFile]) -> list[str]:
    """Rendered paths under ``conformance/`` (always overwritten by sync)."""
    return [path for path in files if path.startswith("conformance/")]
