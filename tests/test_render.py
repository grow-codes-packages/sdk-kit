def test_render_modes_binary_raw_and_flags(kit: Kit) -> None:
    files = render(kit, DEMO)
    script = files["typescript/scripts/run.sh"]
    assert script.mode == 0o755 and script.generated
    assert script.data.decode().endswith("echo demo\n")
    assert files["typescript/client.ts"].mode == 0o644
    assert not files["typescript/client.ts"].generated
    assert files["rust/assets/icon.png"].data == PNG  # binary: tokens untouched
    assert files["docs/logo.png"].data == PNG
    assert files["conformance/core-unit.md"].data == b"# core unit __KEY__ stays raw\n"
    assert files["docker/demo/server.py"].data == b"# demo server __KEY__ stays raw\n"
    assert files["docker/Dockerfile.go"].generated
    assert files["examples/python/quickstart.py"].data == b"// example for DemoClient\n"
    header = files["go/src/core/errors.go"].data.decode().splitlines()[0]
    assert (
        header
        == f'// Generated by sdk-kit {__version__} — do not edit; change sdk-kit and run "sdk-kit sync"'
    )
    assert files["CLAUDE.md"].is_link
    assert not files["README.md"].is_link
    assert sorted(conformance_paths(files)) == [p for p in sorted(files) if p.startswith("conformance/")]


