BLOCK_TEXT = """start
// @sdk-kit:if secrets
secrets-slash
// @sdk-kit:endif
# @sdk-kit:if logging
logging-hash
# @sdk-kit:endif
<!-- @sdk-kit:if tracing -->
tracing-html
<!-- @sdk-kit:endif -->
/* @sdk-kit:if secrets */
secrets-c
/* @sdk-kit:endif */
-- @sdk-kit:if logging
logging-sql
-- @sdk-kit:endif
    # @sdk-kit:if any( logging , tracing )
    telemetry-indented
    # @sdk-kit:endif
end
"""


def test_apply_blocks_all_comment_styles() -> None:
    assert apply_blocks(BLOCK_TEXT, ("secrets",)) == "start\nsecrets-slash\nsecrets-c\nend\n"
    assert (
        apply_blocks(BLOCK_TEXT, ("logging",))
        == "start\nlogging-hash\nlogging-sql\n    telemetry-indented\nend\n"
    )
    assert apply_blocks(BLOCK_TEXT, ("tracing",)) == "start\ntracing-html\n    telemetry-indented\nend\n"
    full = apply_blocks(BLOCK_TEXT, ("secrets", "logging", "tracing"))
    assert "@sdk-kit" not in full
    assert full.count("\n") == 8


def test_apply_blocks_keeps_crlf_and_plain_mentions() -> None:
    text = "a\r\n// @sdk-kit:if tracing\r\nb\r\n// @sdk-kit:endif\r\nsee @sdk-kit:if in docs\r\n"
    assert apply_blocks(text, ("tracing",)) == "a\r\nb\r\nsee @sdk-kit:if in docs\r\n"
    assert apply_blocks("no markers\n", ()) == "no markers\n"


@pytest.mark.parametrize(
    ("text", "message"),
    [
        ("// @sdk-kit:if secrets\n// @sdk-kit:if logging\n// @sdk-kit:endif\n", "do not nest"),
        ("// @sdk-kit:endif\n", "endif without"),
        ("x\n// @sdk-kit:if secrets\nx\n", "f.txt:2: @sdk-kit:if is never closed"),
        ("// @sdk-kit: if secrets\n", "malformed"),
        ("// @sdk-kit:if metrics\n// @sdk-kit:endif\n", "unknown category"),
        ("// @sdk-kit:if any(secrets,metrics)\n// @sdk-kit:endif\n", "unknown category"),
        ("// @sdk-kit:else\n", "malformed"),
    ],
)
def test_apply_blocks_errors(text: str, message: str) -> None:
    with pytest.raises(RenderError, match=message):
        apply_blocks(text, ("secrets",), "f.txt")


