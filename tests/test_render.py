    assert path_categories(PurePosixPath("src/testing/memory-logs.ts"), cfg) == {"logging"}
    assert path_categories(PurePosixPath("pkg/otelhttp.go"), cfg) == {"tracing"}
    cfg2 = TemplateConfig({"tracing": ("src/grow_beta_obs/otel",)})
    assert path_categories(
        PurePosixPath("src/grow___KEY_SNAKE__/otel/x.py"), cfg2, "src/grow_beta_obs/otel/x.py"
    ) == {"tracing"}


