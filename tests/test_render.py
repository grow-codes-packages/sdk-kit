    cfg = TemplateConfig(
        {"logging": ("zapadapter", "src/testing/memory-logs.ts"), "tracing": ("**/otel*.go",)}
    )
    assert path_categories(PurePosixPath("zapadapter/core.go"), cfg) == {"logging"}
